"""Measure the Personalizer: of the variants the published agent writes for true claims, how many
survive the re-check and air, by persona and language, why the rest were dropped, and how long a
request takes over A2A.

    uv run python -m ninety.personalizer.eval --seeds 21,33   # writes runs/eval/personalizer.md

Claims are the fact-checker evaluation's true claims (ninety/eval/factcheck_eval.py) that pass the
code checks, so each starts verified. Each goes through the real path: the A2A client, the A2A
server in process, the published `ninety-personalizer` at its pinned version. Needs Azure; cloud
sessions run it through `.github/workflows/agents-live.yml` (task `personalizer`).
"""

from __future__ import annotations

import argparse
import asyncio
import contextlib
import datetime
import json
import subprocess
import time
from collections import Counter
from pathlib import Path

import httpx

from ninety import config
from ninety.agents.contracts import LANGS, Profile
from ninety.agents.factcheck import check
from ninety.personalizer import core
from ninety.personalizer.client import RemotePersonalizer
from ninety.personalizer.server import create_app

ROOT = Path(__file__).resolve().parents[2]
URL = "http://personalizer.eval/"
PROFILES = [
    Profile(persona, lang, club="home" if persona == "club" else None)
    for persona in core.WRITTEN for lang in LANGS
]


def claims(seeds: list[int], minutes: float, limit: int) -> list[tuple]:
    """Up to `limit` true claims per seed that pass the code checks, with their evidence."""
    from ninety.eval.factcheck_eval import cases

    out = []
    for seed in seeds:
        rows = [r for r in cases(seed, minutes) if r["true"]]
        ok = [r for r in rows if check(r["claim"], {e["id"]: e for e in r["evidence"]}).ok]
        out += [(seed, r["kind"], r["claim"], r["evidence"]) for r in ok[:limit]]
    return out


@contextlib.asynccontextmanager
async def published_personalizer():
    from agent_framework.foundry import FoundryAgent
    from azure.identity import DefaultAzureCredential

    from ninety.agents import foundry

    credential = DefaultAzureCredential()
    name, version = foundry.pinned(core.personalizer_agent(foundry.chat_client(credential)))
    async with FoundryAgent(
        project_endpoint=config.FOUNDRY_PROJECT, agent_name=name, agent_version=version, credential=credential
    ) as agent:

        async def ask(text: str) -> str:
            return (await agent.run(text)).text

        yield ask, f"`{name}:{version}` on `{config.MODEL}`"


async def run(cases: list[tuple], ask, budget_s: float) -> list[dict]:
    app = create_app(core.model_personalizer(ask, timeout_s=budget_s), URL)
    http = httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url=URL, timeout=budget_s)
    client = RemotePersonalizer(URL, budget_s=budget_s, http=http)
    rows = []
    for seed, kind, claim, evidence in cases:  # one at a time, so each time is one request alone
        started = time.perf_counter()
        variants = await client(claim, evidence, PROFILES)
        ms = (time.perf_counter() - started) * 1000
        for i, (p, v) in enumerate(zip(PROFILES, variants, strict=True)):
            why = client.last_dropped.get(i) if client.last_route == "remote" else client.last_route
            rows.append({"seed": seed, "kind": kind, "persona": p.persona, "lang": p.lang,
                         "claim": claim.text, "text": v.text, "dropped": why, "route": client.last_route,
                         "ms": ms})
    return rows


def report(rows: list[dict], label: str, seeds: str) -> str:
    sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True)
    requests = {(r["seed"], r["claim"]): r for r in rows}.values()
    times = sorted(r["ms"] for r in requests)
    lines = [
        "# Personalizer evaluation",
        "",
        f"Generated by `uv run python -m ninety.personalizer.eval` on {datetime.date.today()} at commit "
        f"`{sha.stdout.strip()}`, seeds {seeds}, {label}, budget {core.BUDGET_S} s. {len(requests)} true "
        f"claims, each sent once over A2A for {len(PROFILES)} profiles. A variant *airs* when it passes "
        "the re-check; otherwise the profile gets the verified English text.",
        "",
        "| Persona | Language | Variants | Airs |",
        "|---|---|---|---|",
    ]
    for p in PROFILES:
        mine = [r for r in rows if (r["persona"], r["lang"]) == (p.persona, p.lang)]
        lines.append(f"| {p.persona} | {p.lang} | {len(mine)} | {sum(r['dropped'] is None for r in mine)} |")
    routes = Counter(r["route"] for r in requests)
    # A reason up to its first detail ("number 7 is not ..." keeps its words, not every number).
    dropped = Counter(r["dropped"].split(":")[0] for r in rows if r["dropped"] is not None)
    lines += [
        "",
        f"Requests: {', '.join(f'{n} {route}' for route, n in routes.most_common())}. "
        f"Time per request: p50 {times[len(times) // 2]:.0f} ms, p95 {times[int(len(times) * 0.95)]:.0f} ms, "
        f"max {times[-1]:.0f} ms.",
        "",
        "## Why variants were dropped",
        "",
        *([f"- {n} x {why}" for why, n in dropped.most_common(20)] or ["- none"]),
    ]
    return "\n".join(lines) + "\n"


async def _main(args) -> str:
    seeds = [int(s) for s in args.seeds.split(",")]
    cases = claims(seeds, args.minutes, args.limit)
    async with published_personalizer() as (ask, label):
        rows = await run(cases, ask, args.budget)
    (args.out.with_suffix(".json")).write_text(json.dumps(rows, indent=1, ensure_ascii=False))
    return report(rows, label, args.seeds)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seeds", default="21,33", help="comma-separated simulator seeds (held out)")
    ap.add_argument("--minutes", type=float, default=30)
    ap.add_argument("--limit", type=int, default=10, help="true claims per seed")
    ap.add_argument("--budget", type=float, default=core.BUDGET_S)
    ap.add_argument("--out", type=Path, default=ROOT / "runs/eval/personalizer.md")
    args = ap.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    text = asyncio.run(_main(args))
    args.out.write_text(text)
    print(text)


if __name__ == "__main__":
    main()
