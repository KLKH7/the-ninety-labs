"""What reaches the screen with each part of the fact-checker taken away, on the planted-claim set.

Four variants, every claim of docs/eval/planted-claims-v1.json through each:

- `full`: the fact-checker as it runs (ninety/agents/slice.FactCheckExecutor): the code checks on
  typed facts, then the confidence gate, then the Judge.
- `no fact-checker`: whatever the writer drafts airs.
- `no confidence gate`: the code checks and the Judge.
- `no typed facts`: the Judge alone. The code checks compute with typed fields (ids, numbers,
  players) and the gate reads a typed `confidence`, so without typed facts neither can run. The
  recorded Judge did see typed JSON evidence, so this approximates an untyped fact-checker in its
  favour.

One claim, one draft: a claim the fact-checker stops would go back to the writer for a rewrite in
the full workflow, but the planted claim is what is measured. The Judge's answers are the recorded
ones (ninety/eval/planted.py); its input check (ninety/agents/judge._input_error) is code and runs
for real. A claim that reaches the Judge with no recorded answer is `unmeasured`, never guessed.
tests/test_fact_checker_proof.py checks `full` against the real workflow claim by claim.
"""

from __future__ import annotations

import json
from collections import Counter
from collections.abc import Callable

from ninety.agents.contracts import status_for
from ninety.agents.factcheck import MIN_CONFIDENCE, Claim, Verdict, check, confidence_gate
from ninety.agents.judge import _input_error
from ninety.eval import planted

VARIANTS = ("full", "no fact-checker", "no confidence gate", "no typed facts")
UNMEASURED = "unmeasured"


class NoRecording(LookupError):
    """The Judge was never asked this claim when the set was recorded."""


def recorded_judge(item: dict) -> Verdict:
    """The Judge on one planted claim: its input check, then its recorded answer."""
    if reason := _input_error(item["text"]):
        return Verdict(ok=False, reasons=[f"invalid input: {reason}; claim held back"], category="input")
    if item["judge"] is None:
        raise NoRecording(item["id"])
    return Verdict(**item["judge"])


def known_events(items: list[dict]) -> dict[int, dict[str, dict]]:
    """Per seed, every event the set cites: what the fact-checker can check claims against."""
    known: dict[int, dict[str, dict]] = {}
    for item in items:
        for event in item["events"]:
            known.setdefault(item["seed"], {})[event["id"]] = event
    return known


def screen(item: dict, known: dict[str, dict], variant: str) -> tuple[str, str]:
    """(status, layer): verified, rejected, held or unmeasured, and the layer that decided."""
    if variant == "no fact-checker":
        return "verified", "none"
    claim = Claim(item["text"], list(item["evidence"]))
    layers: list[tuple[str, Callable[[], Verdict]]] = []
    if variant != "no typed facts":
        layers.append(("code checks", lambda: check(claim, known)))
        if variant != "no confidence gate":
            layers.append(("confidence gate", lambda: confidence_gate(claim, known)))
    layers.append(("judge", lambda: recorded_judge(item)))
    for layer, run in layers:
        try:
            verdict = run()
        except NoRecording:
            return UNMEASURED, layer
        if not verdict.ok:
            if layer == "judge" and verdict.category == "input":
                layer = "judge input check"
            return status_for(verdict), layer
    return "verified", "judge"


def run(data: dict | None = None) -> list[dict]:
    data = data or planted.load()
    known = known_events(data["claims"])
    rows = []
    for item in data["claims"]:
        row = {"item": item}
        for variant in VARIANTS:
            row[variant] = screen(item, known[item["seed"]], variant)
        rows.append(row)
    return rows


def aired(row: dict, variant: str) -> bool:
    return row[variant][0] == "verified"


def _frac(n: int, d: int) -> str:
    return f"{n}/{d} ({100 * n / d:.1f}%)" if d else "0/0"


def _header(data: dict, title: str, command: str) -> list[str]:
    return [
        f"# {title}",
        "",
        f"Generated by `{command}` from the planted-claim set "
        f"`docs/eval/planted-claims-v{data['version']}.json` (sha256 `{planted.digest()}`, "
        f"{len(data['claims'])} claims). Offline: the Judge's answers are those recorded from "
        f"{data['source']}; every other layer runs as code. Regenerated byte for byte by the same "
        "command; `tests/test_fact_checker_proof.py` fails if this file is out of date.",
        "",
    ]


def _families(rows: list[dict]) -> list[tuple[str, list[dict]]]:
    out: dict[str, list[dict]] = {}
    for row in rows:
        item = row["item"]
        group = item["family"] if item["family"] != "recorded" else (
            "recorded, true" if item["true"] else "recorded, false")
        out.setdefault(group, []).append(row)
    return list(out.items())


def ablation_report(rows: list[dict], data: dict, command: str) -> str:
    false = [r for r in rows if not r["item"]["true"]]
    true = [r for r in rows if r["item"]["true"]]
    lines = _header(data, "Ablation: what reaches the screen without each part of the fact-checker",
                    command)
    lines += [
        "The same planted claims and seeds through four variants. *False on air* is a planted "
        "false claim the viewer would see; *true on air* a true claim that got through. "
        "*Unmeasured* reached the Judge with no recorded answer, so it is counted neither way.",
        "",
        "| Variant | False on air | True on air | Unmeasured |",
        "|---|---|---|---|",
    ]
    for variant in VARIANTS:
        unmeasured = sum(r[variant][0] == UNMEASURED for r in rows)
        lines.append(
            f"| {variant} | {_frac(sum(aired(r, variant) for r in false), len(false))} "
            f"| {_frac(sum(aired(r, variant) for r in true), len(true))} | {unmeasured} |"
        )
    lines += [
        "",
        "## By family: claims on air",
        "",
        "| Family | Claims | " + " | ".join(VARIANTS) + " |",
        "|---|---|" + "---|" * len(VARIANTS),
    ]
    for family, group in _families(rows):
        cells = []
        for variant in VARIANTS:
            on = sum(aired(r, variant) for r in group)
            unknown = sum(r[variant][0] == UNMEASURED for r in group)
            cells.append(f"{on}" + (f" (+{unknown} unmeasured)" if unknown else ""))
        lines.append(f"| {family} | {len(group)} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "## False claims each removal puts on air",
        "",
        "Every planted false claim the full fact-checker keeps off the screen and the variant airs.",
        "",
    ]
    for variant in VARIANTS[2:]:
        leaked = [r for r in false if aired(r, variant) and not aired(r, "full")]
        unknown = [r for r in false if r[variant][0] == UNMEASURED]
        lines += [f"### {variant}: {len(leaked)} on air, {len(unknown)} unmeasured", ""]
        for kind, n in Counter(r["item"]["kind"] for r in leaked).items():
            example = next(r["item"] for r in leaked if r["item"]["kind"] == kind)
            conf = [e.get("confidence") for e in example["events"] if e.get("confidence") is not None]
            note = f" (cites a detection at confidence {conf[0]:.2f})" if conf else ""
            lines.append(f"- *{kind}*, {n}: \"{example['text']}\"{note}")
        if unknown:
            kinds = Counter(r["item"]["kind"] for r in unknown)
            lines.append("- unmeasured (the Judge was never asked these when recorded): "
                         + ", ".join(f"*{k}* {n}" for k, n in kinds.items()))
        if not leaked and not unknown:
            lines.append("None.")
        lines.append("")
    return "\n".join(lines)


def fact_checker_report(rows: list[dict], data: dict, command: str) -> str:
    false = [r for r in rows if not r["item"]["true"]]
    true = [r for r in rows if r["item"]["true"]]
    caught = [r for r in false if not aired(r, "full") and r["full"][0] != UNMEASURED]
    unmeasured = [r for r in false if r["full"][0] == UNMEASURED]
    wrongly = [r for r in true if not aired(r, "full")]
    lines = _header(data, "Fact-checker on planted claims (offline)", command)
    lines += [
        "The full fact-checker on every planted claim: what it catches, what it wrongly stops, and "
        "which layer decided. *Held* means the claim may be right but nothing airs until it can be "
        "checked (a low-confidence detection, or a Judge outage); *rejected* means it is wrong. "
        f"The confidence gate holds a claim citing a detection below {MIN_CONFIDENCE:.2f}, a design "
        "value until the detector's calibration is measured. The live Judge run this set was "
        "recorded from is `docs/eval/fact-checker.md`.",
        "",
        f"**Planted false claims caught:** {_frac(len(caught), len(false) - len(unmeasured))}"
        + (f", {len(unmeasured)} unmeasured" if unmeasured else "") + ".  ",
        f"**True claims wrongly stopped:** {_frac(len(wrongly), len(true))}.  ",
        f"**Left out of the set:** {data['left_out']['count']} recorded claims, because "
        f"{data['left_out']['why']}.",
        "",
        "| Family | Claims | Caught or aired correctly | Rejected | Held | Decided by |",
        "|---|---|---|---|---|---|",
    ]
    for family, group in _families(rows):
        truth = group[0]["item"]["true"]
        right = sum(aired(r, "full") == truth and r["full"][0] != UNMEASURED for r in group)
        status = Counter(r["full"][0] for r in group)
        layers = Counter(r["full"][1] for r in group if not aired(r, "full"))
        decided = ", ".join(f"{k} {n}" for k, n in sorted(layers.items())) or "none stopped"
        word = "aired" if truth else "caught"
        lines.append(f"| {family} | {len(group)} | {right}/{len(group)} {word} | {status['rejected']} "
                     f"| {status['held']} | {decided} |")
    lines += ["", "## By kind", "", "| Kind | Claims | Result |", "|---|---|---|"]
    for kind in dict.fromkeys(r["item"]["kind"] for r in rows):
        group = [r for r in rows if r["item"]["kind"] == kind]
        truth = group[0]["item"]["true"]
        right = sum(aired(r, "full") == truth for r in group)
        lines.append(f"| {kind} | {len(group)} | {right}/{len(group)} {'aired' if truth else 'caught'} |")
    lines += ["", "## Every miss and wrong stop", ""]
    misses = [r for r in rows if aired(r, "full") != r["item"]["true"] or r["full"][0] == UNMEASURED]
    for r in misses:
        item = r["item"]
        status, layer = r["full"]
        why = "; ".join((item["judge"] or {}).get("reasons") or []) if layer == "judge" else ""
        lines.append(f"- *{item['kind']}* (seed {item['seed']}, {item['id']}): \"{item['text']}\" "
                     f"{status} by {layer}" + (f": {why}" if why else ""))
    if not misses:
        lines.append("None.")
    return "\n".join(lines) + "\n"


def results(rows: list[dict]) -> str:
    """Every claim's status under every variant, for anyone to recount."""
    return json.dumps(
        [{"id": r["item"]["id"], "kind": r["item"]["kind"], "true": r["item"]["true"],
          **{v: {"status": r[v][0], "layer": r[v][1]} for v in VARIANTS}} for r in rows],
        indent=1,
    ) + "\n"
