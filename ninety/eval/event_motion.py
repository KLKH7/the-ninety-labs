"""How far an event's reference object moves when an event is timed early or late, measured on
simulator truth. It is the evidence for judging a detected event's spot at the detected time
(ninety/eval/event_score.py): a timing error becomes a place error at the object's speed.

    uv run python -m ninety.eval.event_motion            # writes docs/eval/event-motion.md
"""

from __future__ import annotations

import argparse
import datetime
import math
import platform
import statistics
from collections import Counter, defaultdict
from pathlib import Path

from ninety.eval.event_score import NOT_PLACED, git_commit, reference_point
from ninety.sim.engine import simulate

ROOT = Path(__file__).resolve().parents[2]
OFFSETS_S = (0.04, 0.2, 0.4, 0.6, 1.0)  # one frame up to the full time window


def quantile(xs: list[float], q: float) -> float:
    xs = sorted(xs)
    return xs[min(len(xs) - 1, int(q * len(xs)))]


def measure(seed: int, minutes: float) -> dict:
    m = simulate(seed, minutes)
    moved = defaultdict(lambda: defaultdict(list))  # type -> offset -> metres
    speed = defaultdict(list)
    close, pairs = Counter(), Counter()
    last: dict[tuple[str, str], dict] = {}
    for e in m.events:
        if e["type"] in NOT_PLACED:
            continue
        spot = (e["x"], e["y"])
        here = reference_point(e["type"], e["team"], e["t"], m.frames, spot)
        if here is None:
            continue
        speed[e["type"]].append(math.hypot(here[2], here[3]))
        for off in OFFSETS_S:
            for sign in (-1, 1):
                there = reference_point(e["type"], e["team"], e["t"] + sign * off, m.frames, spot)
                if there is not None:
                    moved[e["type"]][off].append(math.hypot(there[0] - here[0], there[1] - here[1]))
        key = (e["type"], e["team"])
        if key in last:
            pairs[e["type"]] += 1
            if e["t"] - last[key]["t"] <= 1.0:
                close[e["type"]] += 1
        last[key] = e
    return {"moved": moved, "speed": speed, "close": close, "pairs": pairs}


def report(seeds: list[int], minutes: float) -> str:
    lines = [
        "# Event motion: how a timing error becomes a place error",
        "",
        f"Generated by `uv run python -m ninety.eval.event_motion` on {datetime.date.today().isoformat()}, "
        f"commit `{(git_commit() or 'unknown')[:7]}`; seeds {', '.join(map(str, seeds))}, "
        f"{minutes:g} minutes each; Python {platform.python_version()} on {platform.system()}. "
        "Simulator truth only: no detector numbers. The same seed simulates the same match on any "
        "operating system (lesson 48), so these digits reproduce anywhere at this commit.",
        "",
        "For every event, the distance its reference object (the ball; the nearest player of the "
        "team for pressure and kick-off) moves between the event's frame and a frame early or late "
        "by the offset. This is why `ninety/eval/event_score.py` judges a detected spot at the "
        "detected time: judged at the true event's spot, a pass detected 0.4 s late would be "
        "metres off even if vision placed it perfectly.",
        "",
        "The last column counts consecutive events of one type and team that are within 1.0 s of "
        "each other: how often place would be needed to tell two events apart.",
    ]
    for seed in seeds:
        r = measure(seed, minutes)
        lines += ["", f"## Seed {seed}", "",
                  "| Type | Events | Speed at the event, median / 90th pct (m/s) | "
                  + " | ".join(f"Moved in {o:g} s, median / 90th pct (m)" for o in OFFSETS_S)
                  + " | Same-team pairs within 1.0 s |",
                  "|---|---|---|" + "---|" * len(OFFSETS_S) + "---|"]
        for kind in sorted(r["speed"]):
            sp = r["speed"][kind]
            moved = r["moved"][kind]
            cells = [f"{statistics.median(moved[o]):.1f} / {quantile(moved[o], 0.9):.1f}" for o in OFFSETS_S]
            lines.append(f"| {kind} | {len(sp)} | {statistics.median(sp):.1f} / {quantile(sp, 0.9):.1f} | "
                         + " | ".join(cells) + f" | {r['close'][kind]} of {r['pairs'][kind]} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description="Measure how far event reference objects move in time.")
    ap.add_argument("--seeds", type=int, nargs="+", default=[7, 11])
    ap.add_argument("--minutes", type=float, default=30)
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "eval" / "event-motion.md")
    args = ap.parse_args(argv)
    args.out.write_text(report(args.seeds, args.minutes))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
