MINUTE = 2
SEEDS = (21, 33)  # the held-out seeds (lesson 11): the live run's other two grounds
UNSURE = 0.3  # the low-confidence row's confidence for the ground's side pass: below MIN_CONFIDENCE
JUDGE_TIMEOUT_S = 0.05  # production: judge.judge's default; short here so the row runs in a blink
HANG_S = 60.0  # longer than any timeout here: a call that never answers


def claim_on(event_id: str, known: dict[str, dict]) -> Claim:
    """A true claim about one detected pass, worded from its facts. It names neither player nor side:
    a detection may name nobody (ninety/vision/events.py, attribution), and the M1 clip's sides were
    told with team_confidence 0.529, so a claim naming a team is held by the confidence gate
    (factcheck.MIN_TEAM_CONFIDENCE). This table measures how failures are handled, not team naming,
    which tests/test_confidence_gate.py covers."""
    e = known[event_id]
    return Claim(f"A completed pass of {e['distance_m']} m at {e['ball_speed_kmh']} km/h.", [event_id])


def claim_in_spanish(event_id: str, known: dict[str, dict]) -> str:
    """The same claim worded in Spanish for the stand-in Personalizer: written here, by us, not a
    model's or a service's translation."""
    e = known[event_id]
    return f"Un pase completado de {e['distance_m']} m a {e['ball_speed_kmh']} km/h."


def reply(claim: Claim) -> str:
    return json.dumps({"text": claim.text, "evidence": claim.evidence})


def picks(main: str, evidence: list[str]) -> str:
    return json.dumps({"moments": [{"main_event": main, "evidence": evidence}]})


SUPPORTED = json.dumps({"statements": [
    {"text": "the claim", "kind": "fact", "verdict": "supported", "reason": "matches the event"},
]})


class JudgeAgent:
    """Stands in for the published Judge inside the real wrapper: supports, or never answers."""

    def __init__(self, hang: bool = False):
        self.hang, self.asked = hang, 0

    async def run(self, prompt: str):
        self.asked += 1
        if self.hang:
            await asyncio.sleep(HANG_S)
        return SimpleNamespace(value=None, text=SUPPORTED)


async def outage(prompt: str) -> str:
    raise ServiceRequestError("injected: the Foundry endpoint cannot be reached")


def nobody_listening() -> str:
    """A local address nothing listens on: a connection to it is refused at once, as when the
    Personalizer's container is down."""
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        port = s.getsockname()[1]
    return f"http://127.0.0.1:{port}"


def personalizer_down(agent) -> dict:
    # The real A2A client (its budget, its outage rule, its in-process fallback), to a dead address.
    return {"personalizer": RemotePersonalizer(nobody_listening(), budget_s=2.0)}


@dataclass(frozen=True)
class Ground:
    """Where a scenario runs: a match, its events, and two completed passes in the minute (the
    moment's main event and a second one offered as evidence)."""

    match: str
    events: tuple[dict, ...]
    main: str
    side: str


def detections(ground: Ground) -> bool:
    """Whether the ground's events are detections, with a confidence: the M1 clip's are; a held-out
    seed's are the simulator's stand-ins, which have none."""
    return all(e.get("source") != "truth" for e in ground.events)


def applicable(ground: Ground) -> list[Scenario]:
    """The scenarios a ground can run: the low-confidence row needs detections to be unsure of."""
    return [s for s in SCENARIOS if detections(ground) or not s.unsure_side]


def ground_of(match: str, events: list[dict]) -> Ground:
    """A match's minute as a ground: its first two completed passes, the main one and the side one.
    Picked by what they are, never by id: a detected event's id is its place in the clip's order
    (ninety/vision/events.py), so a new kind of event moves every id after it."""
    from ninety.match.facts import compact

    passes = [e["id"] for e in events if compact(e)["minute"] == MINUTE and e["type"] == "pass"
              and e.get("outcome") == "success"]
    if len(passes) < 2:
        raise ValueError(f"{match}: fewer than two completed passes in minute {MINUTE}")
    return Ground(match, tuple(events), passes[0], passes[1])


def m1_ground() -> Ground:
    """The M1 clip's detected events (the confident completed pass at 66.88 s, confidence 0.80, and
    the one at 73.72 s)."""
    events, _, _ = workflow.detected_events(match_server.DETECTED[detected.M1_CLIP]())
    return ground_of(detected.M1_CLIP, events)


def seed_ground(seed: int) -> Ground:
    """A held-out seed's minute, the simulator's events."""
    return ground_of(match_server.match_id(seed), workflow.simulated_events(seed, match_server.MINUTES))


@dataclass(frozen=True)
class Scenario:
    name: str
    injected: str  # what failed, in words
    unsure_side: bool = False  # the second pass is detected at UNSURE confidence
    cites_side: bool = False  # the Tactician's claim is about the second pass
    override: Callable[[JudgeAgent], dict] = lambda agent: {}
    judge_hangs: bool = False
    claim: str = "held"  # how the moment's claim must end, exactly
    fallback: str = ""  # the trace step this failure's fallback must mark ("role: what"); "" for none


SCENARIOS = [
    Scenario("none", "nothing (the baseline)", claim="verified"),
    Scenario("judge timeout",
             f"the Judge never answers (every call outlasts its timeout, retried {RETRY_LIMIT} time(s))",
             judge_hangs=True, fallback="producer: held: timeout"),
    Scenario("tactician outage", "the Tactician's Foundry endpoint cannot be reached",
             override=lambda agent: {"tactician": outage}, fallback="tactician: template"),
    Scenario("personalizer down", "the Personalizer's service refuses the connection (its container is down)",
             override=personalizer_down, claim="verified", fallback="personalizer: personalizer: refused"),
    Scenario("low confidence",
             f"the detector reports the event the Tactician cites at confidence {UNSURE}, "
             f"below {MIN_CONFIDENCE}",
             unsure_side=True, cites_side=True, fallback="producer: held: low_confidence"),
]


def events_for(scenario: Scenario, ground: Ground | None = None) -> list[dict]:
    ground = ground or m1_ground()
    return [{**e, "confidence": UNSURE} if scenario.unsure_side and e["id"] == ground.side else dict(e)
            for e in ground.events]


def models_for(
    scenario: Scenario, known: dict[str, dict], ground: Ground | None = None
) -> tuple[Models, JudgeAgent]:
    ground = ground or m1_ground()
    agent = JudgeAgent(hang=scenario.judge_hangs)
    cited = ground.side if scenario.cites_side else ground.main
    replies = {
        "analyst": [picks(ground.main, [ground.main, ground.side])],
        "tactician": [reply(claim_on(cited, known))],
        "challenger": ['{"agree": true}'],
    }
    judge = functools.partial(judge_call, agent, timeout_seconds=JUDGE_TIMEOUT_S)
    # A working Personalizer's stand-in: each persona keeps the claim's words, and its Spanish is
    # the scripted wording above (claim_in_spanish), so a Spanish profile airs Spanish.
    from ninety.personalizer import translate

    spanish = {claim_on(i, known).text: claim_in_spanish(i, known) for i in (ground.main, ground.side)}

    async def scripted_translation(text: str, lang: str) -> str:
        if lang != "es" or text not in spanish:
            raise translate.TranslationUnavailable(f"no scripted {lang} wording for {text!r}")
        return spanish[text]

    personalizer = translate.translated(Models.scripted().personalizer, scripted_translation)
    fakes = {"personalizer": personalizer, **scenario.override(agent)}
    return Models.scripted(replies, judge=judge, **fakes), agent


def run(scenario: Scenario, ground: Ground | None = None) -> dict:
    """One row: run the minute with the failure injected, and record what the viewer would see."""
    from ninety.match.facts import compact

    ground = ground or m1_ground()
    events = events_for(scenario, ground)
    known = {e["id"]: compact(e) for e in workflow.agent_events(events)}
    models, agent = models_for(scenario, known, ground)

    async def go():
        try:
            return await workflow.run_workflow(models, events, MINUTE, ground.match, personalize=True)
        finally:
            if isinstance(models.personalizer, RemotePersonalizer):
                await models.personalizer.close()

    return row(scenario, asyncio.run(go()), agent.asked, ground)


def injection(scenario: Scenario, counter: list[int], known: dict[str, dict],
              ground: Ground, opened: list | None = None) -> Callable[[Models], Models]:
    """For --live: the scenario's failure in place of the live model, every Judge call counted. A
    claim on the unsure detection is injected at the Analyst (the moment that offers it) and the
    Tactician (the claim): live models would not reliably cite it, and the row is about what the
    gate does when one does."""
    from dataclasses import replace

    def inject(models: Models) -> Models:
        agent = JudgeAgent(hang=True)
        swapped = scenario.override(agent)
        if scenario.cites_side:
            moment = picks(ground.main, [ground.main, ground.side])
            cited = reply(claim_on(ground.side, known))

            async def analyst(prompt: str) -> str:
                return moment

            async def tactician(prompt: str) -> str:
                return cited

            swapped = {**swapped, "analyst": analyst, "tactician": tactician}
        judge = (functools.partial(judge_call, agent, timeout_seconds=JUDGE_TIMEOUT_S)
                 if scenario.judge_hangs else models.judge)

        async def counted(claim, evidence):
            counter[0] += 1
            return await judge(claim, evidence)

        if opened is not None and isinstance(swapped.get("personalizer"), RemotePersonalizer):
            opened.append(swapped["personalizer"])  # the caller closes it
        return replace(models, judge=counted, **swapped)

    return inject


async def live_rows(seeds: tuple[int, ...] = SEEDS) -> list[list[dict]]:
    """Every scenario with the published agents, one live minute each (agents-live): on the M1
    clip and on each held-out seed. One credential, signed in before the seeds are simulated (a
    simulation can outlast agents-live's five-minute sign-in), serves every minute.

    Every agent reads the one match this commit simulated: the Analyst gets the minute's events
    inline under a match id no server serves, and a call to the match tools fails the call
    (foundry.ReadTheTools). The deployed tools serve the matches the deployed image simulated with
    its own engine, and through Foundry took 50.7 and 55.3 s on the M1 clip against the 60 s budget
    (2.6 and 1.3 s inline; measured by hand on 2026-10-20, PR #182: lesson 90). The Personalizer
    is the published one behind the A2A server in this process, so the Spanish profiles get Spanish;
    without it every variant is the verified English text."""
    from ninety.agents import credentials
    from ninety.match.facts import compact
    from ninety.personalizer import core
    from ninety.personalizer.client import in_process

    tables = []
    async with credentials.new_credential() as credential:
        await credentials.sign_in(credential)
        grounds = [m1_ground(), *(seed_ground(s) for s in seeds)]
        async with core.published_ask(credential) as (ask, _):
            for ground in grounds:
                out = []
                for scenario in applicable(ground):
                    events, counter, opened = events_for(scenario, ground), [0], []
                    known = {e["id"]: compact(e) for e in workflow.agent_events(events)}
                    opened.append(in_process(core.model_personalizer(ask)))
                    try:
                        result, *_ = await workflow.run_live(
                            lambda events=events: events, MINUTE, match_server.unserved(ground.match), True,
                            False, trace_to="none", personalize=True, credential=credential,
                            personalizer=opened[0],
                            inject=injection(scenario, counter, known, ground, opened),
                        )
                    finally:
                        for client in opened:
                            await client.close()
                    out.append(row(scenario, result, counter[0], ground))
                tables.append(out)
    return tables


def minute_claim(reviews: list[Review]) -> Review | None:
    """The claim the row shows: the one that aired, else the Analyst's first moment's. The scripted
    Analyst offers one moment, the main pass; a live Analyst picks its own, so a row looked up by
    the main pass's id found none whenever the model preferred another moment. Recovery reads
    every moment's status (`ends_as_it_must`), not this one alone."""
    return next((r for r in reviews if r.aired is not None), reviews[0] if reviews else None)


def ends_as_it_must(statuses: list[str], expected: str) -> bool:
    """Every moment of the minute, not one: held means each one held; verified means one aired and
    none held (a claim the fact-checker rejected is the system working, not a failure)."""
    if expected == "held":
        return bool(statuses) and all(s == "held" for s in statuses)
    return "verified" in statuses and "held" not in statuses


def variant_gaps(result, known: dict[str, dict]) -> dict[str, list[str]]:
    """For each aired claim, the profiles it was personalized for whose variant did not air in its
    own language: refused by the fact-checker, reading as English (language.reads_english), or
    never returned."""
    from ninety.personalizer.cues import profiles_for
    from ninety.personalizer.language import reads_english

    refused = [s.detail for s in result.trace if s.role == "fact_checker"
               and s.action in ("held", "rejected") and "/" in s.detail.split(":")[0]]
    insights = [c for c in result.cues if c["kind"] == "insight"]
    english = [f"{c['persona']}/{c['lang']}: {c['text']}" for c in insights
               if c.get("lang", "en") != "en" and reads_english(c["text"])]
    shown = {(tuple(c["evidence"]), c["persona"], c.get("lang", "en")) for c in insights}
    gone = {d.split(":")[0] for d in refused}
    missing = []
    for review in result.reviews:
        if review.aired is None or not review.aired.evidence:
            continue
        evidence = tuple(review.aired.evidence)
        for p in profiles_for(known[evidence[0]]):
            name = f"{p.persona}/{p.lang}"
            if (evidence, p.persona, p.lang) not in shown and name not in gone:
                missing.append(name)
    return {"refused": refused, "english": english, "missing": missing}


def row(scenario: Scenario, result, judge_asked: int, ground: Ground) -> dict:
    from ninety.match.facts import compact

    # Each aired text checked again here, by the code checks, against the minute's events: a
    # measurement of what aired, independent of the `verified` flag the cue carries.
    known = {e["id"]: compact(e) for e in workflow.agent_events(events_for(scenario, ground))}
    review = minute_claim(result.reviews)
    templates = sorted(c["id"] for c in result.cues if c["kind"] != "insight")
    insights = [c for c in result.cues if c["kind"] == "insight"]
    fallback = [f"{s.role} {s.action}: {s.detail}".rstrip(": ") for s in result.trace
                if s.action in ("fail", "skip", "template", "held", "hold", "fallback", "error")]
    verdict = review.primary if review else None
    return {
        "scenario": scenario.name,
        "match": ground.match,
        "unsure": [ground.side] if scenario.unsure_side else [],
        "injected": scenario.injected,
        "status": review.status if review else "none",
        "statuses": [r.status for r in result.reviews],
        "category": verdict.category if verdict else None,
        "reasons": list(verdict.reasons) if verdict else [],
        "judge_asked": judge_asked,
        "insights": [{"text": c["text"], "persona": c["persona"], "lang": c.get("lang", "en"),
                      "verified": c.get("verified", False),
                      "passes_check": check(Claim(c["text"], list(c["evidence"])), known).ok}
                     for c in insights],
        "templates": templates,
        "badges": sorted({c["fallback"] for c in result.cues if c.get("fallback")}),
        "trace_fallbacks": [f"{s.role}: {s.fallback}" for s in result.trace if s.fallback],
        "fallback": fallback,
        **{f"variants_{k}": v for k, v in variant_gaps(result, known).items()},
        "model_calls": result.model_calls,
    }


def recovered(row: dict, base: dict) -> dict[str, bool]:
    """Each part of recovery, checked against the failure-free run."""
    lost = set(base["templates"]) - set(row["templates"])
    gated = {i for i in lost if any(i.startswith(f"cue-{e}-") for e in row["unsure"])}
    return {
        "templates stay": lost == gated and set(row["templates"]) <= set(base["templates"]),
        "nothing unverified airs": all(i["verified"] and i["passes_check"] for i in row["insights"]),
        "claim ends as it must": ends_as_it_must(row["statuses"], CLAIM[row["scenario"]]),
        # This failure's own fallback, marked in the trace; none at all without a failure.
        "fallback recorded": (FALLBACK[row["scenario"]] in row["trace_fallbacks"])
        if FALLBACK[row["scenario"]] else row["trace_fallbacks"] == [],
        # The viewer shows a cue's `fallback` as a badge: on screen in every failure, never without one.
        "fallback badge on screen": bool(row["badges"]) == (row["scenario"] != "none"),
        # Without a failure every profile gets its own variant in its own language: a Spanish
        # profile held on the English text, shown English, or left out is a defect, so the baseline
        # fails (the reviewer's ruling).
        "every variant airs without a failure": row["scenario"] != "none" or not (
            row["variants_refused"] or row["variants_english"] or row["variants_missing"]),
    }


CLAIM = {s.name: s.claim for s in SCENARIOS}
FALLBACK = {s.name: s.fallback for s in SCENARIOS}


def rows(out: list[dict] | None = None) -> list[dict]:
    out = [run(s) for s in SCENARIOS] if out is None else out
    base = out[0]
    for row in out:
        row["recovered"] = recovered(row, base)
        row["recovers"] = all(row["recovered"].values())
    return out


def results(table: list[dict], live: bool = False) -> str:
    # Strict JSON: another program reads it (lesson 43).
    body = {"command": COMMAND + (" --live" if live else ""), "clip": detected.M1_CLIP, "minute": MINUTE,
            "models": "the published Foundry agents" if live else "stand-ins", "rows": table}
    return json.dumps(body, indent=1, allow_nan=False) + "\n"


def table_lines(table: list[dict]) -> list[str]:
    """The table and its recovery count, as both the offline and the live report show them."""
    base = table[0]
    failures = [r for r in table if r["scenario"] != "none"]
    lines = [
        "| Injected failure | Claim | Fallbacks and holds in the trace | On screen | Recovers |",
        "|---|---|---|---|---|",
    ]
    for r in table:
        aired = (f"verified insight \"{r['insights'][0]['text']}\"" if r["insights"] else "no insight")
        kept = len(r["templates"])
        screen = (f"{kept} template graphics (as with no failure); {aired}" if kept == len(base["templates"])
                  else f"{kept} of {len(base['templates'])} template graphics (the ones on the unsure "
                       f"detection are not drawn); {aired}")
        if r["badges"]:
            screen += "; badge: " + ", ".join(f"FALLBACK ({b})" for b in r["badges"])
        why = f"{r['status']}" + (f" ({r['category']})" if r["category"] else "")
        if r["scenario"] != "none" and r["judge_asked"] == 0:
            why += ", Judge not asked"
        fb = "; ".join(r["fallback"]) or "none needed"
        verdict = "yes" if r["recovers"] else "**no**"
        lines.append(f"| {r['injected']} | {why} | {fb} | {screen} | {verdict} |")
    ok = sum(r["recovers"] for r in failures)
    lines += [
        "",
        f"**Baseline: {'passes' if base['recovers'] else 'fails'}. Recovered: {ok} of {len(failures)}**"
        " injected failures. A row recovers when every template",
        "graphic stays on air (less those on an unsure detection, which the confidence gate keeps off",
        "the screen), every aired text passes the code checks again, every moment's claim ends as it",
        "must (each held; verified when only the Personalizer failed, since the insight needs no",
        "Personalizer: one aired and none held), the failure's own fallback is marked in the trace, and",
        "a fallback badge is on screen (the cue's `fallback`, which the viewer draws). The baseline has",
        "neither, and must air every profile's variant: none refused, none missing, and no Spanish one",
        "reading as English (more English function words than Spanish, `personalizer/language.py`).",
        "That test is a heuristic: it does not count quoted words or capitalised names, and English",
        "padded with Spanish function words reads as Spanish. The on-air gate holds the same.",
    ]
    held_es = [r for r in table if any("/es:" in step for step in r["fallback"])]
    if held_es:
        down = sum(any(f.startswith("personalizer:") for f in r["trace_fallbacks"]) for r in held_es)
        lines += [
            f"In {len(held_es)} of {len(table)} rows the Spanish variants are held, since a variant airs",
            f"only in its own language: in {down} the Personalizer was down and its fallback is the",
            f"English text; in {len(held_es) - down} the Personalizer answered and its Spanish did not pass.",
        ]
    return lines


def production_judge_timeout() -> float:
    """The Judge's own default timeout (ninety/agents/judge.judge), as production calls it."""
    import inspect

    return inspect.signature(judge_call).parameters["timeout_seconds"].default


def report(table: list[dict], live: bool = False, ground: str = detected.M1_CLIP) -> str:
    title = "# Failure table: injected failures in the multi-agent workflow"
    lines = [title + (f", live, {ground}" if live else ""), ""]
    if live:
        lines += [
            f"Generated by `{COMMAND} --live` in agents-live: each row is one live minute (minute",
            f"{MINUTE} of `{ground}`) with the published Foundry agents doing everything but the injected",
            "failure. The run covers the M1 clip and the held-out seeds 21 and 33; the seeds' events are the",
            "simulator's stand-ins, with no detection confidence, so the low-confidence row runs on the M1",
            "clip only. Live models vary from run to run; this file is committed as the run wrote it. The",
            "offline, byte-for-byte table is `docs/eval/failure-table.md`.",
            "",
        ]
        return "\n".join(lines + table_lines(table) + [""])
    lines += [
        f"Generated by `{COMMAND}` (offline, byte for byte; `--check` fails if this file",
        "is stale, as `tests/test_workflow_failures.py` does). Each row runs the workflow itself",
        "(`ninety/agents/workflow.run_workflow`: template graphics, Analyst, Tactician, Challenger, the",
        "fact-checking agent with its confidence gate, Producer) on the M1 clip's detected events",
        f"(`{detected.M1_CLIP}`, minute {MINUTE}), with one failure injected at the model boundary.",
        "The Judge is the real wrapper (its retry, timeout and verdicts) around a stand-in agent; the",
        "other models are scripted; the Personalizer's Spanish is a wording we wrote for the table",
        "(`claim_in_spanish`), not a translation by a model or a service.",
        "Data: `docs/eval/failure-table.json`. The M1 live path's own table",
        "is `docs/eval/failure-table-m1.md`.",
        "",
    ]
    lines += table_lines(table)
    lines += [
        "",
        "## Budgets",
        "",
        f"- The Judge: {production_judge_timeout():g} s per call in production, retried {RETRY_LIMIT}",
        "  time(s), then the claim is held (fail closed).",
        f"  Here {JUDGE_TIMEOUT_S} s, so the timeout row runs the same code path in a blink.",
        "- The Personalizer: `personalizer.core.BUDGET_S` per call in production; on a timeout, a 5xx or",
        "  a refused connection the in-process fallback answers (the verified text), here after the",
        "  refusal, so the row takes milliseconds.",
        f"- A writer (Analyst, Tactician, Challenger): {workflow.MODEL_TIMEOUT_SECONDS:.0f} s in production"
        " (`workflow.MODEL_TIMEOUT_SECONDS`), then its claim is held and the template stays.",
        f"- The confidence gate: a claim citing a detection below {MIN_CONFIDENCE} is held before the Judge",
        "  is asked, and never rewritten; a template graphic is drawn only for a detection at or above it.",
        "",
        "Latencies are not measured here: the models are stand-ins, so a time would describe the stand-in.",
        "",
    ]
    return "\n".join(lines)


def render() -> dict[Path, str]:
    table = rows()
    return {OUT_MD: report(table), OUT_JSON: results(table)}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if a committed file is out of date")
    ap.add_argument("--live", action="store_true", help="the published agents around each failure (Azure)")
    ap.add_argument("--out", type=Path, default=ROOT / "runs" / "eval", help="--live: where to write")
    args = ap.parse_args()
    logging.getLogger("agent_framework").setLevel(logging.WARNING)  # its superstep chatter
    if args.live:
        tables = [rows(t) for t in asyncio.run(live_rows())]
        args.out.mkdir(parents=True, exist_ok=True)
        commit = workflow._commit()  # the engine the seeds were simulated with, and everything else
        reports = "\n".join(report(t, live=True, ground=t[0]["match"]) for t in tables)
        # The workflow's agents and the Personalizer, as run_live and core.published_ask pin them.
        from ninety.agents import evidence, foundry
        from ninety.personalizer.core import personalizer_agent

        defs = evidence.of_code(
            lambda client: [*foundry.workflow_agents(client).values(), personalizer_agent(client)]
        )
        md = (f"Run at commit `{commit}` (the engine that simulated the seeds, and the rest).\n\n"
              f"{evidence.md_line(defs)}\n\n{reports}")
        body = {"command": COMMAND + " --live", "commit": commit, "minute": MINUTE,
                "models": "the published Foundry agents", evidence.KEY: defs,
                "grounds": [{"match": t[0]["match"], "rows": t} for t in tables]}
        for name, text in (("failure-table-live.md", md),
                           ("failure-table-live.json", json.dumps(body, indent=1, allow_nan=False) + "\n")):
            (args.out / name).write_text(text)
            print(f"wrote {args.out / name}")
        for t in tables:
            print(f"{t[0]['match']}: baseline {'passes' if t[0]['recovers'] else 'fails'}; "
                  f"recovered {sum(r['recovers'] for r in t[1:])} of {len(t) - 1}")
        return
    out = render()
    if args.check:
        stale = [p for p, text in out.items() if not p.exists() or p.read_text() != text]
        if stale:
            names = ", ".join(str(p.relative_to(ROOT)) for p in stale)
            sys.exit(f"out of date: {names}; run {COMMAND}")
        print("up to date")
        return
    for path, text in out.items():
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
