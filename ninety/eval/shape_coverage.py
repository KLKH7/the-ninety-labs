"""How many of a team's 11 a shape fact needs tracked: the measurement that sets
`ninety.intel.shape.MIN_TRACKED`, by the plan in docs/eval/shape-coverage-plan.md.

    uv run python -m ninety.eval.shape_coverage --out docs/eval/shape-coverage

Grading use only: it reads the simulator's positions as the reference (AGENTS.md: the answer key is
for grading), never anything on the live path.
"""

from __future__ import annotations

import argparse
import json
import math
import random
from pathlib import Path

from ninety.intel import shape

SEEDS = (7, 11)  # docs/eval/shape-coverage-plan.md: S4's seeds, never a test seed
MINUTES = 10
KS = range(4, shape.TEAM_SIZE + 1)
DRAWS = 20
RNG_SEED = 0
GEOMETRY = (*shape.DISTANCES, "area")
QUANTILE = 0.9


def _quantile(values: list[float], q: float) -> float:
    """The q-quantile, nearest rank (the smallest value with at least q of the values at or below)."""
    ordered = sorted(values)
    return ordered[max(0, math.ceil(q * len(ordered)) - 1)]


def _keep(frames: list[dict], team: str, ids: set[str]) -> list[dict]:
    return [{**f, "players": [p for p in f["players"] if p["team"] != team or p["id"] in ids]}
            for f in frames]


def errors(
    windows: list[tuple[str, list[dict]]], scheme: str, k: int, rng: random.Random
) -> dict[str, list[float]]:
    """Each geometry metric's error at k tracked, as a share of its tolerance (1 is the tolerance)."""
    out: dict[str, list[float]] = {m: [] for m in GEOMETRY}
    for team, frames in windows:
        full = shape.window_shape(frames, team)
        roster = sorted({p["id"] for f in frames for p in f["players"] if p["team"] == team})
        middle = frames[len(frames) // 2]
        ball = middle["ball"]
        where = {p["id"]: (p["x"], p["y"]) for p in middle["players"]}
        draws = DRAWS if scheme == "random" else 1
        for _ in range(draws):
            if scheme == "random":
                ids = set(rng.sample(roster, k))
            else:
                spot = (ball["x"], ball["y"])
                near = sorted(roster, key=lambda i: math.dist(where.get(i, (1e9, 1e9)), spot))
                ids = set(near[:k])
            part = shape.window_shape(_keep(frames, team, ids), team)
            for m in GEOMETRY:
                if m not in full:
                    continue
                tol = full["perimeter"] * shape.POSITION_ERROR_M if m == "area" else shape.POSITION_ERROR_M
                # A metric k players cannot measure at all is as wrong as it gets: count it failed.
                out[m].append(abs(part[m] - full[m]) / tol if m in part else math.inf)
    return out


def measure() -> dict:
    from ninety.match.tracking import slim
    from ninety.sim.engine import simulate

    windows: list[tuple[str, list[dict]]] = []
    for seed in SEEDS:
        run = simulate(seed, MINUTES)
        by_minute: dict[int, list[dict]] = {}
        for f in run.frames:
            by_minute.setdefault(shape.minute_of(f["t"]), []).append(slim(f))
        for frames in by_minute.values():
            for team in ("home", "away"):
                if sum(p["team"] == team for p in frames[0]["players"]) == shape.TEAM_SIZE:
                    windows.append((team, frames))
    rng = random.Random(RNG_SEED)
    table: dict[str, dict[int, dict[str, float]]] = {}
    passing: dict[str, int] = {}
    for scheme in ("random", "far_from_ball"):
        table[scheme] = {}
        for k in KS:
            errs = errors(windows, scheme, k, rng)
            # null: k players could not measure it at all (strict JSON has no infinity, lesson 43).
            table[scheme][k] = {m: None if math.isinf(q := _quantile(v, QUANTILE)) else round(q, 3)
                                for m, v in errs.items() if v}
        passing[scheme] = min(
            (k for k in KS if all(q is not None and q <= 1.0 for q in table[scheme][k].values())),
            default=shape.TEAM_SIZE,
        )
    return {"seeds": list(SEEDS), "minutes": MINUTES, "windows": len(windows), "draws": DRAWS,
            "quantile": QUANTILE, "position_error_m": shape.POSITION_ERROR_M,
            "p90_error_over_tolerance": table, "smallest_k_passing": passing,
            "min_tracked": max(passing.values())}


def report(result: dict) -> str:
    lines = [
        "# Shape facts: how many tracked players a fact needs",
        "",
        "Generated by `uv run python -m ninety.eval.shape_coverage --out docs/eval/shape-coverage` "
        "by the plan in [shape-coverage-plan.md](shape-coverage-plan.md), committed first.",
        f"Seeds {', '.join(map(str, result['seeds']))}, {result['minutes']} simulated minutes each: "
        f"{result['windows']} team-minutes with all 11 on the pitch. Each cell is the 90th-percentile "
        "error at k tracked, as a share of its tolerance (1.26 m; for the area, the hull's perimeter "
        "times 1.26 m). A cell at or below 1.00 passes. `inf`: k players could not measure it at all.",
        "",
    ]
    for scheme, rows in result["p90_error_over_tolerance"].items():
        metrics = list(next(iter(rows.values())))
        lines += [f"## Missing {scheme.replace('_', ' ')}", "",
                  "| k tracked | " + " | ".join(metrics) + " |", "|---" * (len(metrics) + 1) + "|"]
        for k, cells in rows.items():
            shown = ("inf" if cells[m] is None else f"{cells[m]:.2f}" for m in metrics)
            lines.append(f"| {k} | " + " | ".join(shown) + " |")
        lines += ["", f"Smallest k passing every metric: **{result['smallest_k_passing'][scheme]}**.", ""]
    lines += [f"**MIN_TRACKED = {result['min_tracked']}** (the larger of the two schemes)."]
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, required=True, help="write <out>.json and <out>.md")
    args = ap.parse_args()
    result = measure()
    args.out.with_suffix(".json").write_text(json.dumps(result, indent=2, allow_nan=False) + "\n")
    args.out.with_suffix(".md").write_text(report(result))
    print(report(result))


if __name__ == "__main__":
    main()
