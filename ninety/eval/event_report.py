"""The event detector on the frozen test set, scored once (docs/eval/detector-plan.md, step D).

    uv run python -m ninety.eval.event_report --test-dir runs/test-frozen-cca498c/test \\
        --observations docs/eval/attribution --observations tests/fixtures --out docs/eval/event-report-v2

For each test clip: its observations (the image stage's output, judged by observe.place) give the
detected events (ninety/vision/events.py), graded by event_score (strict and lenient) and the
positions by pitch_score. Pooled over the clips, per event type. Grading, so it reads the answer key;
nothing on the live path imports it.
"""

from __future__ import annotations

import argparse
import datetime
import json
from pathlib import Path

from ninety.eval import event_score, pitch_score
from ninety.eval.attribution_score import observations_file, ratio, write_or_check
from ninety.eval.event_score import wilson
from ninety.vision import events as ev
from ninety.vision import track as tr

SEEDS = (900001, 900002, 900003, 900004, 900005)
COMMAND = ("uv run python -m ninety.eval.event_report --test-dir runs/test-frozen-cca498c/test "
           "--observations docs/eval/attribution --observations tests/fixtures "
           "--out docs/eval/event-report-v2")


def clip(seed: int, test_dir: Path, dirs: list[Path]) -> dict:
    root = test_dir / f"seed{seed}"
    rows = tr.read_observations(observations_file(seed, dirs))
    frames = [json.loads(x) for x in (root / "frames.jsonl").read_text().splitlines() if x.strip()]
    truth = event_score.load_events(root / "events.jsonl", "truth")
    detected, summary = ev.detect(rows)
    report = event_score.score(truth, detected, frames)
    pitch = pitch_score.score(frames, rows)
    return {"seed": seed, "detected": detected, "summary": summary, "events": report,
            "positions": {k: pitch[k] for k in ("frames", "players", "ball_on_ground", "ball_in_the_air")}}


# The clip the detector was first developed on (#143): its scores are reported pooled with the
# others and also left out, since several constants still keep the values set while looking at it
# (docs/eval/detector-plan.md, inventory).
DEVELOPED_ON = 900001
def pooled(clips: list[dict], rule: str) -> dict:
    out = {}
    for kind in sorted({k for c in clips for k in c["events"][rule]["per_type"]}):
        rows = [c["events"][rule]["per_type"].get(kind) for c in clips]
        tp = sum(r["tp"] for r in rows if r)
        fp = sum(r["fp"] for r in rows if r)
        fn = sum(r["fn"] for r in rows if r)
        p, r = ratio(tp, tp + fp), ratio(tp, tp + fn)
        f1 = None if p is None or r is None else (2 * p * r / (p + r) if p + r else 0.0)
        out[kind] = {"true": tp + fn, "detected": tp + fp, "tp": tp, "fp": fp, "fn": fn,
                     "precision": p, "recall": r, "f1": f1,
                     "precision_95": wilson(tp, tp + fp), "recall_95": wilson(tp, tp + fn)}
    return out


def report_md(body: dict) -> str:
    lines = [
        "# Event detection from video: the frozen test set, scored once",
        "",
        f"Generated by `{body['command']}` at commit `{body['commit']}`, {body['date']}. The side naming,",
        "the camera trust test, the side vote and RIVAL_M were re-derived on validation clips; the event",
        "and tracker thresholds were tried there and kept; the camera search, the marking pixels, the kit",
        "colour sampling and the kit clustering's settings keep the values set while developing on test",
        f"seed {DEVELOPED_ON} ([detector-plan.md](detector-plan.md)). Every constant was frozen before",
        "this score.",
        "",
    ]
    ps = body["pooled"]["strict"].get("pass")
    pw = body["pooled_without_developed_on"]["strict"].get("pass")
    for label, r in (("All five clips", ps), (f"Without seed {DEVELOPED_ON}", pw)):
        if r:
            lines.append(f"- **{label}, passes, strict:** {r['tp']} of {r['true']} found, {r['fp']} false; "
                         f"precision {r['precision']:.2f} (95% {r['precision_95']}), "
                         f"recall {r['recall']:.2f} "
                         f"(95% {r['recall_95']}), F1 {r['f1']:.2f}.")
    lines.append("")
    for rule in ("strict", "lenient", "time_only"):
        lines += [f"## {rule.replace('_', ' ').capitalize()}", "",
                  "| Type | True | Detected | TP | FP | FN | Precision | Recall | F1 |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for kind, r in body["pooled"][rule].items():
            f = lambda v: "-" if v is None else f"{v:.2f}"  # noqa: E731
            lines.append(f"| {kind} | {r['true']} | {r['detected']} | {r['tp']} | {r['fp']} | "
                         f"{r['fn']} | {f(r['precision'])} | {f(r['recall'])} | {f(r['f1'])} |")
        lines.append("")
    lines += ["## Per clip", "",
              "| Seed | Camera trusted | Players median / p90 (m) | Ball on ground median / p90 (m) "
              "| Events detected | Strict pass F1 |", "|---|---|---|---|---|---|"]
    for c in body["clips"]:
        pos = c["positions"]
        pf1 = c["events"]["strict"]["per_type"].get("pass", {}).get("f1")
        lines.append(f"| {c['seed']} | {pos['frames']['camera_ok']} of {pos['frames']['observed']} | "
                     f"{pos['players']['median_m']} / {pos['players']['p90_m']} | "
                     f"{pos['ball_on_ground']['median_m']} / {pos['ball_on_ground']['p90_m']} | "
                     f"{c['summary']['events']} | {'-' if pf1 is None else f'{pf1:.2f}'} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--test-dir", type=Path, required=True)
    ap.add_argument("--observations", type=Path, action="append", required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    clips = [clip(s, a.test_dir, a.observations) for s in SEEDS]
    body = {
        "command": COMMAND, "commit": event_score.git_commit(),
        "date": datetime.date.today().isoformat(),
        "pooled": {rule: pooled(clips, rule) for rule in ("strict", "lenient", "time_only")},
        "pooled_without_developed_on": {rule: pooled([c for c in clips if c["seed"] != DEVELOPED_ON], rule)
                                        for rule in ("strict", "lenient", "time_only")},
        "clips": [{k: v for k, v in c.items() if k != "detected"} for c in clips],
    }
    write_or_check(a.out, body, report_md, a.check)
    print(json.dumps({k: v.get("pass") for k, v in body["pooled"].items()}, indent=1))


if __name__ == "__main__":
    main()
