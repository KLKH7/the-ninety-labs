"""How far each player's top speed and sprint count from tracked positions are from the truth.

Grading only (AGENTS.md): this reads the simulator's truth. A simulated match is spoiled as the
tracker spoils it (ninety/eval/roles_eval.spoil: fragments, a persistent position error, players
missing, swaps); each true player's tracks are merged by their owner (what the name rule does for a
named player, lesson 241); and ninety/intel/physical.rows is run on both, over the same minutes.

    uv run python -m ninety.eval.physical_eval runs/f21-65247ba3 --minutes 30 --out docs/eval/physical.json
"""

from __future__ import annotations

import argparse
import json
import statistics
from collections import defaultdict
from pathlib import Path

from ninety.eval import roles_eval
from ninety.intel import physical


def per_player(rows, owner=None) -> dict[str, dict]:
    out: dict[str, dict] = defaultdict(lambda: {"top_kmh": 0.0, "sprints": 0, "m": 0.0})
    for r in rows:
        who = owner[r["track"]] if owner else r["track"]
        p = out[who]
        p["top_kmh"] = max(p["top_kmh"], r["top_kmh"])
        p["sprints"] += r["sprints"]
        p["m"] += r["m"]
    return dict(out)


def grade(run: Path, minutes: float, fragment_s: float = roles_eval.FRAGMENT_S[0], seed: int = 1) -> dict:
    frames, _ = roles_eval.load(run, step=25)
    frames = [f for f in frames if f["t"] <= minutes * 60]
    spoilt, owner = roles_eval.spoil(frames, seed, fragment_s)
    true, seen = per_player(physical.rows(frames)), per_player(physical.rows(spoilt), owner)
    both = [p for p in true if p in seen]
    top_err = [seen[p]["top_kmh"] - true[p]["top_kmh"] for p in both]
    s_true, s_seen = sum(true[p]["sprints"] for p in both), sum(seen[p]["sprints"] for p in both)
    return {
        "players": len(both),
        "top_speed_error_kmh": {
            "median": round(statistics.median(top_err), 1),
            "min": round(min(top_err), 1),
            "max": round(max(top_err), 1),
        },
        "sprints": {
            "true": s_true, "tracked": s_seen, "ratio": round(s_seen / s_true, 2) if s_true else None
        },
        "rows": [
            {
                "player": p,
                "top_true": round(true[p]["top_kmh"], 1),
                "top_tracked": round(seen[p]["top_kmh"], 1),
                "sprints_true": true[p]["sprints"],
                "sprints_tracked": seen[p]["sprints"],
            }
            for p in sorted(both)
        ],
    }


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("run", type=Path)
    ap.add_argument("--minutes", type=float, default=30.0)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args(argv)
    report = {"run": args.run.name, "minutes": args.minutes, "sprint_kmh": physical.SPRINT_KMH,
              "by_fragment": {str(fs): grade(args.run, args.minutes, fs) for fs in roles_eval.FRAGMENT_S}}
    args.out.write_text(json.dumps(report, indent=1) + "\n")
    lines = [
        "# Players' top speed and sprints, graded against the truth",
        "",
        f"Generated by `uv run python -m ninety.eval.physical_eval runs/{args.run.name} --minutes "
        f"{args.minutes:g}`: the simulated match spoiled as the tracker spoils it, each true player's tracks "
        f"merged, a step a second, sprints above {physical.SPRINT_KMH} km/h held for a second.",
        "",
        "| Fragment mean | Players | Top speed, tracked − true, median (range) | Sprints, tracked / true |",
        "|---|---|---|---|",
    ]
    for fs, g in report["by_fragment"].items():
        e, sp = g["top_speed_error_kmh"], g["sprints"]
        lines.append(
            f"| {float(fs):g} s | {g['players']} | {e['median']} km/h ({e['min']} to {e['max']}) | "
            f"{sp['tracked']} / {sp['true']} ({sp['ratio']}) |"
        )
    args.out.with_suffix(".md").write_text("\n".join(lines) + "\n")
    brief = {fs: {k: v for k, v in g.items() if k != "rows"} for fs, g in report["by_fragment"].items()}
    print(json.dumps(brief))


if __name__ == "__main__":
    main()
