"""The late drop in high-intensity running (docs/GROUNDING.md, R7), judged by the protocol fixed in
docs/EVALUATION.md before any engine change was measured against it: the same 30 seeds every
time, the mean drop over matches with its spread, beside the published band. A report, never a
gate, and never a target: no constant is chosen by looking at it (docs/LESSONS.md, lesson 2).

    uv run python -m ninety.sim.late_drop     # 30 full matches; writes docs/eval/late-drop.md
"""

from __future__ import annotations

import argparse
import math
import subprocess
from concurrent.futures import ProcessPoolExecutor
from datetime import date
from pathlib import Path
from statistics import mean, stdev

from ninety.sim.patterns import HIGH_INTENSITY, PUBLISHED_KM, PUBLISHED_TOP, measure

ROOT = Path(__file__).resolve().parents[2]
# The protocol (docs/EVALUATION.md, "Late drop in high-intensity running"). Fixed before any
# number was measured with it; changing any of these starts a new protocol, it does not tune one.
SEEDS = tuple(range(101, 131))  # 30 matches, never chosen by their result
MINUTES = 90
BAND = (0.20, 0.45)  # R7: last 15 minutes about 20% (Bradley 2009) to 35-45% (Mohr 2003) below the first 15
T_975 = {29: 2.045}  # Student's t, two-sided 95%, by degrees of freedom (30 matches: 29)


def summarise(drops: list[float]) -> dict[str, float]:
    """The mean of the per-match drops, their standard deviation, a 95% interval for the mean,
    and the range of single matches."""
    n = len(drops)
    sd = stdev(drops) if n > 1 else 0.0
    half = T_975.get(n - 1, 1.96) * sd / math.sqrt(n)  # other sizes: the normal approximation
    m = mean(drops)
    return {"n": n, "mean": m, "sd": sd, "lo": m - half, "hi": m + half,
            "min": min(drops), "max": max(drops)}


def verdict(s: dict[str, float], band: tuple[float, float] = BAND) -> str:
    """The rule fixed in the protocol: the mean is inside the band or not; the interval only says
    whether that reading is firm or sits on an edge."""
    lo, hi = band
    if not lo <= s["mean"] <= hi:
        return "outside the published band"
    if s["lo"] < lo or s["hi"] > hi:
        return "inside the published band, but its 95% interval crosses an edge"
    return "inside the published band"


def pct(d: float) -> str:
    return f"{d * 100:.0f}%"


def report(results: list[dict], commit: str) -> str:
    drops = [r["late_drop"] for r in results]
    s = summarise(drops)
    lines = [
        "# Late drop in high-intensity running (R7)",
        "",
        f"Generated by `uv run python -m ninety.sim.late_drop` on {date.today().isoformat()}, engine "
        f"commit `{commit}`, by the protocol in [EVALUATION.md](../EVALUATION.md#late-drop-in-high-"
        f"intensity-running-r7): seeds {SEEDS[0]} to {SEEDS[-1]} ({len(SEEDS)} matches, "
        f"{MINUTES} minutes each, no half-time break), outfield players, high intensity above "
        f"{HIGH_INTENSITY} m/s (19.8 km/h). A report, never a target.",
        "",
        f"**Mean late drop: {pct(s['mean'])}** (SD {pct(s['sd'])} across matches; 95% interval for "
        f"the mean {pct(s['lo'])} to {pct(s['hi'])}; single matches {pct(s['min'])} to "
        f"{pct(s['max'])}). Published: {pct(BAND[0])} to {pct(BAND[1])} (Bradley 2009; Mohr 2003). "
        f"**Verdict: {verdict(s)}.**",
        "",
        "A negative drop means more high-intensity running in the last 15 minutes than the first.",
        "",
        "| Seed | First 15 min, m | Last 15 min, m | Drop | Slow store left at 90 min |",
        "|---|---|---|---|---|",
    ]
    for r in results:
        lines.append(f"| {r['seed']} | {r['early_high']:.0f} | {r['late_high']:.0f} "
                     f"| {pct(r['late_drop'])} | {pct(r['store_left'])} |")
    lines += [
        "",
        "## The same matches by position (R2, R6, O8)",
        "",
        "| Position | Distance, km | Published, km | Top speed, m/s | Published top speed, m/s |",
        "|---|---|---|---|---|",
    ]
    for group in PUBLISHED_KM:
        rows = [x for r in results for x in r["groups"].get(group, [])]
        lines.append(f"| {group} | {mean(x['km'] for x in rows):.1f} | {PUBLISHED_KM[group]} "
                     f"| {mean(x['top'] for x in rows):.1f} | {PUBLISHED_TOP[group]} |")
    lines += [
        "",
        f"Slow store (P10) left at the final whistle, mean over outfield players and matches: "
        f"{pct(mean(r['store_left'] for r in results))}.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=ROOT / "docs/eval/late-drop.md")
    args = ap.parse_args()
    with ProcessPoolExecutor() as pool:
        results = list(pool.map(measure, SEEDS))
    commit = subprocess.run(["git", "describe", "--always", "--dirty"], capture_output=True, text=True,
                            cwd=ROOT).stdout.strip() or "unknown"
    text = report(results, commit)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    print(text)


if __name__ == "__main__":
    main()
