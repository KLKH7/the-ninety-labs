"""Does the passer's estimate predict what the engine does? A report, never a target: nothing in the
engine is tuned to it.

In a share of decisions a random forward pass is forced instead of the player's choice, so the
estimate is also tested on passes nobody would pick. Each pass's estimate (decisions.pass_confidence
for the way it is struck) is compared with whether a team-mate received it.

    uv run python -m ninety.sim.calibration     # 6 matches; writes docs/eval/pass-calibration.md
"""

from __future__ import annotations

import argparse
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from ninety.sim import fmath

ROOT = Path(__file__).resolve().parents[2]
FORCE_SHARE = 0.15  # the share of decisions with a forced forward pass
FORWARD_M = 5.0  # a forced pass goes at least this far toward the goal attacked
BINS = ((0.0, 0.1), (0.1, 0.3), (0.3, 0.5), (0.5, 0.7), (0.7, 0.9), (0.9, 1.01))


def measure(seed: int, minutes: float = 90) -> list[tuple[float, bool, bool, bool]]:
    """(estimate, forced, lofted, received) for every pass the decisions chose or were forced to."""
    from ninety.sim import decisions as D
    from ninety.sim.engine import Engine

    rng = fmath.Random(f"{seed}-calibration")
    pending: dict[str, tuple[float, bool, bool]] = {}
    original = D.choose

    def choose(scene, r, *rest):
        forward = [o for o in D.options(scene) if o.kind == "pass"
                   and (o.target[0] - scene.x) * D.attack(scene.goal_x) > FORWARD_M]
        forced = bool(forward) and rng.random() < FORCE_SHARE
        o = rng.choice(forward) if forced else original(scene, r, *rest)
        if o.kind == "pass":
            mate = next(m for m in scene.mates if m[0] == o.receiver)
            c = D.pass_confidence(scene, *o.target, mate[1], mate[2], mate[3], o.lofted, o.pace, o.receiver)
            pending["next"] = (c, forced, o.lofted)
        else:
            pending.pop("next", None)
        return o

    D.choose = choose
    try:
        e = Engine(seed)
        rows = []
        kick = e.pass_to

        def pass_to(*a, **k):
            n = len(e.match.events)
            kick(*a, **k)
            struck = [x for x in e.match.events[n:] if x["type"] == "pass"]
            if struck and "next" in pending and not k.get("throw"):
                rows.append((struck[-1], *pending.pop("next")))

        e.pass_to = pass_to
        e.run(minutes)
    finally:
        D.choose = original
    return [(c, forced, lofted, ev.get("outcome") == "success") for ev, c, forced, lofted in rows]


def table(rows: list[tuple[float, bool, bool, bool]]) -> list[str]:
    out = ["| Estimate | Passes | Mean estimate | Received |", "|---|---|---|---|"]
    for lo, hi in BINS:
        b = [r for r in rows if lo <= r[0] < hi]
        if b:
            out.append(f"| {lo:.1f} to {min(hi, 1.0):.1f} | {len(b)} | {sum(r[0] for r in b) / len(b):.2f} | "
                       f"{sum(r[3] for r in b) / len(b):.2f} |")
    brier = sum((r[0] - r[3]) * (r[0] - r[3]) for r in rows) / max(1, len(rows))
    out.append(f"\nBrier score {brier:.3f} over {len(rows)} passes.")
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seeds", default="1,2,3,4,5,6")
    ap.add_argument("--minutes", type=float, default=90)
    ap.add_argument("--out", default=str(ROOT / "docs/eval/pass-calibration.md"))
    args = ap.parse_args()
    seeds = [int(s) for s in args.seeds.split(",")]
    with ProcessPoolExecutor() as pool:
        rows = [r for rs in pool.map(measure, seeds, [args.minutes] * len(seeds)) for r in rs]
    forced = [r for r in rows if r[1]]
    chosen = [r for r in rows if not r[1]]
    lines = ["# Pass-estimate calibration", "",
             f"Generated by `uv run python -m ninety.sim.calibration` on seeds {args.seeds}, "
             f"{args.minutes:g} minutes each. In {FORCE_SHARE:.0%} of decisions a random forward pass is "
             "forced. A report, never a target.", "", "## Forced forward passes", "", *table(forced), "",
             "## Passes the players chose", "", *table(chosen)]
    Path(args.out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines[4:]))


if __name__ == "__main__":
    main()
