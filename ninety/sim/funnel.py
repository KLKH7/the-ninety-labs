"""How a simulated match moves the ball up the pitch: possessions, entries, shots, goals, duels,
beside published figures. A report, never a fitting target: nothing in the engine is tuned to these
numbers (docs/GROUNDING.md, R rows). Goals a team over the 12 matches are also a held-out check
(R4): they must fall where a real league's 12 matches would (`goals_range`, lesson 118).

    uv run python -m ninety.sim.funnel    # 12 matches; writes docs/eval/funnel.md
"""

from __future__ import annotations

import argparse
import math
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path
from statistics import mean, stdev

from ninety.sim.engine import simulate

ROOT = Path(__file__).resolve().parents[2]
PITCH_X, PITCH_Y = 105.0, 68.0
FINAL_THIRD_M = PITCH_X / 3  # from the goal attacked
BOX_DEPTH_M, BOX_HALF_WIDTH_M = 16.5, 20.16  # Law 1
# Per team per match, for reading the report only, from docs/GROUNDING.md R3 (itself *verify*).
# A measure with no sourced figure is left blank rather than given a number nobody can trace.
PUBLISHED = {"passes": "450 to 500 (R3, *verify*)", "completion": "75 to 88% (R3, *verify*)"}
SEEDS = (7, 11, 21, 31, 41, 51, 61, 71, 81, 91, 101, 111)
# R4: goals a match in the Premier League, the lowest and highest season in the league's own table
# of 2014-15 to 2023-24 (premierleague.com, 25 April 2024): 2.57 in 2014-15, 3.26 in 2023-24 (335 of
# its 380 matches played).
GOALS_A_MATCH = (2.57, 3.26)
GOALS_MISS_RATE = 0.01  # design: how often a league scoring like the real one may fail the check


def poisson_quantile(lam: float, q: float) -> int:
    """The smallest k with P(X <= k) >= q, for X Poisson with mean lam."""
    term = cdf = math.exp(-lam)
    k = 0
    while cdf < q:
        k += 1
        term *= lam / k
        cdf += term
    return k


def goals_range(matches: int, miss: float = GOALS_MISS_RATE) -> tuple[float, float]:
    """Goals a team a match that `matches` real matches show, but for a share `miss` of samples.

    A match's goals are Poisson (Maher 1982, *Statistica Neerlandica* 36: 109-118), so the goals of
    n matches are Poisson with n times the mean. The low end is the leanest season's lower tail,
    the high end the richest season's upper tail, `miss / 2` each.
    """
    low = poisson_quantile(GOALS_A_MATCH[0] * matches, miss / 2)
    high = poisson_quantile(GOALS_A_MATCH[1] * matches, 1 - miss / 2)
    return low / (2 * matches), high / (2 * matches)


def zone(x: float, y: float, goal_x: float) -> str | None:
    depth = abs(goal_x - x)
    if depth <= BOX_DEPTH_M and abs(y - PITCH_Y / 2) <= BOX_HALF_WIDTH_M:
        return "box"
    return "final_third" if depth <= FINAL_THIRD_M else None


def measure(seed: int, minutes: float = 90) -> dict[str, float]:
    return tally(simulate(seed, minutes))


def tally(m) -> dict[str, float]:
    """Per team, averaged over the two teams. A possession runs from one team's controlled touch
    until the other team's (a loose ball, or one in flight, still belongs to it). An entry is the
    ball crossing into the zone during a possession, once per crossing; a possession that starts
    inside a zone has not entered it."""
    team_of = {r["id"]: r["team"] for r in m.roster}
    goal_x = {"home": PITCH_X, "away": 0.0}
    out = {k: 0.0 for k in ("possessions", "final_third", "box")}
    team, inside = None, set()
    for f in m.frames:
        holder = team_of.get(f.get("possessor"))
        if team is None and not holder:
            continue
        z = zone(f["ball"]["x"], f["ball"]["y"], goal_x[holder or team])
        now = {"final_third", "box"} if z == "box" else ({z} if z else set())
        if holder and holder != team:
            team, inside = holder, now
            out["possessions"] += 1
        for k in now - inside:
            out[k] += 1
        inside = now
    ev = m.events
    passes = [e for e in ev if e["type"] == "pass"]
    out["passes"] = len(passes)
    out["completion"] = sum(e.get("outcome") == "success" for e in passes) / max(1, len(passes))
    for kind in ("shot", "goal", "tackle", "interception"):
        out[kind + "s"] = sum(e["type"] == kind for e in ev)
    return {k: (v if k == "completion" else v / 2) for k, v in out.items()}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seeds", default=",".join(map(str, SEEDS)))
    ap.add_argument("--minutes", type=float, default=90)
    ap.add_argument("--out", default=str(ROOT / "docs/eval/funnel.md"))
    args = ap.parse_args()
    seeds = [int(s) for s in args.seeds.split(",")]
    with ProcessPoolExecutor() as pool:
        runs = list(pool.map(measure, seeds, [args.minutes] * len(seeds)))
    lines = ["# Match funnel", "",
             f"Generated by `uv run python -m ninety.sim.funnel` on seeds {args.seeds}, {args.minutes:g} "
             "minutes each. Per team per match. A report beside published figures, never a target.", "",
             "| Measure | Engine | Published |", "|---|---|---|"]
    for k in ("passes", "completion", "possessions", "final_third", "box", "shots", "goals", "tackles",
              "interceptions"):
        v = mean(r[k] for r in runs)
        shown = f"{v:.0%}" if k == "completion" else f"{v:.1f}"
        lines.append(f"| {k.replace('_', ' ')} | {shown} | {PUBLISHED.get(k, '')} |")
    goals = [r["goals"] for r in runs]
    low, high = goals_range(len(runs))
    error = stdev(goals) / math.sqrt(len(goals)) if len(goals) > 1 else float("nan")
    lines += ["", f"Goals a team: {mean(goals):.2f} (standard error {error:.2f}, lesson 89). "
              f"A real league's {len(runs)} matches show {low:.2f} to {high:.2f}, "
              f"but for {GOALS_MISS_RATE:.0%} of samples (R4): "
              f"{'inside' if low <= mean(goals) <= high else 'OUTSIDE'}."]
    Path(args.out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines[4:]))


if __name__ == "__main__":
    main()
