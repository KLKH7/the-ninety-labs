"""How often the keeper saves: isolated central shots against a keeper set where O1 puts him, and
the shots on target in full matches. A report, never a gate: nothing in the engine is tuned to
these numbers (docs/GROUNDING.md, O1 and P15).

    uv run python -m ninety.sim.saves    # 200 shots per distance and 12 matches; writes docs/eval/saves.md
"""

from __future__ import annotations

import argparse
import math
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from ninety.sim import ball, offball, shape
from ninety.sim.engine import PITCH_Y, Engine, simulate

ROOT = Path(__file__).resolve().parents[2]
GOAL_X = 105.0  # the away side defends this goal; the home side shoots
DISTANCES_M = (8, 11, 16, 20, 25)
AFTER_S = 3.0  # how long after the strike the ball is followed
MATCH_SEEDS = (7, 11, 21, 31, 41, 51, 61, 71, 81, 91, 101, 111)  # the funnel's seeds
FAR_X = {"home": 20.0, "away": 30.0}  # everyone else, well away from the shot


def shoot_from(distance: float, seed: int) -> dict[str, bool] | None:
    """One central shot from `distance` m by the home side's best finisher, the ball against his
    body as he faces goal, with the away keeper at his O1 spot and nobody else near. The keeper is
    placed, not left to come out: with no defender the shooter is through on goal and the keeper
    would rush him (O1), which is a different case."""
    e = Engine(seed)
    shooter = max((p for p in e.players if p.team == "home" and p.role != "GK"),
                  key=lambda p: p.profile["finishing"])
    keeper = e.keeper("away")
    others = [p for p in e.players if p is not shooter and p is not keeper]
    for i, p in enumerate(others):
        p.x, p.y = FAR_X[p.team], 5.0 + 3.0 * i
    for p in e.players:
        p.vx = p.vy = 0.0
    bx = GOAL_X - distance
    shooter.x, shooter.y, shooter.heading = bx - shape.surface(0.0, 0.0, pad=ball.RADIUS), PITCH_Y / 2, 0.0
    e.ball = (bx, PITCH_Y / 2, 0.0, 0.0, 0.0, 0.0)
    e.restart = None
    e.give(shooter.id)
    keeper.x, keeper.y = offball.keeper_spot(bx, PITCH_Y / 2, GOAL_X)
    keeper.heading = math.pi
    e.shoot(shooter)
    shot = e.kicked if e.kicked and e.kicked["type"] == "shot" else None
    if shot is None:
        return None
    touched = False
    for _ in range(int(AFTER_S * 25)):
        touched = touched or e.shot_touched_by == "keeper"
        if e.kicked is not shot or any(ev["type"] == "goal" for ev in e.match.events):
            break
        e.step()
    goal = any(ev["type"] == "goal" for ev in e.match.events)
    return {"on_target": goal or shot.get("outcome") == "on_target", "saved": touched and not goal}


def _shot(job: tuple[float, int]) -> tuple[float, dict[str, bool] | None]:
    return job[0], shoot_from(*job)


def match_shots(seed: int) -> dict[str, int]:
    """Shots in one 90-minute match: goals, and on target but not scored (saved or stopped)."""
    shots = [e for e in simulate(seed, 90).events if e["type"] == "shot"]
    return {"goal": sum(e.get("outcome") == "goal" for e in shots),
            "saved": sum(e.get("outcome") == "on_target" for e in shots)}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--n", type=int, default=200, help="shots per distance")
    ap.add_argument("--out", default=str(ROOT / "docs/eval/saves.md"))
    args = ap.parse_args()
    jobs = [(d, s) for d in DISTANCES_M for s in range(1, args.n + 1)]
    with ProcessPoolExecutor() as pool:
        rows = [(d, r) for d, r in pool.map(_shot, jobs, chunksize=10) if r]
        matches = list(pool.map(match_shots, MATCH_SEEDS))
    lines = ["# Saves", "",
             f"Generated by `uv run python -m ninety.sim.saves`: {args.n} central shots from each distance "
             "(seeds 1 up), the home side's best finisher against the away keeper set at his O1 spot "
             f"with nobody else near, and the shots in {len(MATCH_SEEDS)} full matches (the funnel's "
             "seeds). A report, never a target.", "",
             "| Shot | Saved, of those on target |", "|---|---|"]
    for d in DISTANCES_M:
        on = [r for dd, r in rows if dd == d and r["on_target"]]
        share = f"{sum(r['saved'] for r in on) / len(on):.0%} of {len(on)}" if on else "none"
        lines.append(f"| isolated, {d} m | {share} |")
    goals, saved = sum(m["goal"] for m in matches), sum(m["saved"] for m in matches)
    lines.append(f"| in matches | {saved / max(1, goals + saved):.0%} of {goals + saved} |")
    Path(args.out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines[4:]))


if __name__ == "__main__":
    main()
