"""How often a keeper saves isolated shots: an average shooter alone, straight in front of goal, at
each distance, against a keeper where the engine stands him (O1) or on his line. A report, never a
gate: nothing in the engine is tuned to these numbers (docs/GROUNDING.md P15 and O1).

    uv run python -m ninety.sim.saves    # writes docs/eval/saves.md
"""

from __future__ import annotations

import argparse
import math
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from ninety.sim import ball, shape
from ninety.sim.engine import FPS, PITCH_X, PITCH_Y, Engine, goal_x, other
from ninety.sim.offball import KEEPER_DEPTH, RUSH_RANGE_M

ROOT = Path(__file__).resolve().parents[2]
DISTANCES_M = (8, 11, 16, 20, 25, 30)
FAR_X_M = 10.0  # everyone else waits by the other goal: nobody can reach the shot in its flight
SHOT_LIMIT_S = 6.0  # a bound only: a shot ends when it is saved, goes in or goes out


def shoot_once(seed: int, dist: float, keeper_spot: str, depths: list[float] | None = None) -> str | None:
    """One isolated shot: the outcome the engine records (goal, on_target, off_target). A shot still
    loose after SHOT_LIMIT_S (parried, nobody near) is closed as the engine would close it. How far
    off his line the keeper started is appended to `depths`, if given."""
    e = Engine(seed)
    team = "home"
    gx = goal_x(team)
    shooter = e.by_id["h9"]
    keeper = e.keeper(other(team))
    shooter.profile.attributes.update(finishing=0.5, composure=0.5, weak_foot=0.5)
    away = math.copysign(1.0, PITCH_X / 2 - gx)  # from that goal back up the pitch
    for i, q in enumerate(e.players):
        q.vx = q.vy = 0.0
        if q is not shooter and q is not keeper:
            q.x, q.y = gx + away * (PITCH_X - FAR_X_M), 5.0 + 3.0 * (i % 20)
    shooter.x, shooter.y = gx + away * dist, PITCH_Y / 2
    shooter.heading = math.atan2(0.0, gx - shooter.x)
    foot = shape.surface(shooter.heading, shooter.heading, pad=ball.RADIUS)  # at his feet, before him
    e.ball = (shooter.x + math.cos(shooter.heading) * foot, shooter.y, 0.0, 0.0, 0.0, 0.0)
    e.possessor = e.last_touch = shooter.id
    e.poss_team = team
    if keeper_spot == "line":
        keeper.x, keeper.y = gx + away * KEEPER_DEPTH[0], PITCH_Y / 2  # O1's shallowest depth
    elif keeper_spot == "none":  # a control: an empty net, the keeper waiting with the others
        keeper.x, keeper.y = gx + away * (PITCH_X - FAR_X_M), PITCH_Y / 2
    else:
        # where the engine stands him (O1): within RUSH_RANGE_M of goal an unmarked shooter is through
        # on goal, so he is already out closing him down
        keeper.x, keeper.y, _ = e.shape_target(keeper)
    if depths is not None:
        depths.append(abs(gx - keeper.x))
    keeper.heading = math.atan2(shooter.y - keeper.y, shooter.x - keeper.x)
    e.shoot(shooter)
    shot = e.kicked
    if not shot or shot["type"] != "shot":
        return None
    for _ in range(int(SHOT_LIMIT_S * FPS)):
        e.step()
        if shot.get("outcome"):
            return shot["outcome"]
    if e.kicked is shot:  # parried or blocked and still loose, with nobody near to collect it
        e.close_shot(shot, e.ball[0], e.ball[1])  # the engine's own call, from who touched it
        return shot["outcome"]
    return None



def measure(dist: float, keeper_spot: str, trials: int) -> dict[str, float]:
    out: dict[str, float] = {"goal": 0, "on_target": 0, "off_target": 0, "blocked": 0, "unresolved": 0}
    depths: list[float] = []
    for seed in range(trials):
        out[shoot_once(seed, dist, keeper_spot, depths) or "unresolved"] += 1
    out["depth"] = sum(depths) / len(depths)
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--trials", type=int, default=200)
    ap.add_argument("--out", default=str(ROOT / "docs/eval/saves.md"))
    args = ap.parse_args()
    jobs = [(d, spot) for spot in ("o1", "line") for d in DISTANCES_M]
    with ProcessPoolExecutor() as pool:
        runs = list(pool.map(measure, *zip(*jobs, strict=True), [args.trials] * len(jobs)))
    lines = ["# Isolated shots", "",
             f"Generated by `uv run python -m ninety.sim.saves` with {args.trials} shots per row "
             f"(seeds 0 to {args.trials - 1}): an average shooter (finishing, composure, weak foot "
             "0.5) alone, straight in front of goal; the keeper as each seed draws him, on his line "
             f"({KEEPER_DEPTH[0]:g} m out) or where the engine stands him (O1). With nobody else near, "
             f"a shooter within {RUSH_RANGE_M:g} m of goal is through on goal, so there the O1 keeper "
             "starts already out, closing him down. Saved: on-target shots that did not go in. A "
             "report, never a target.", "",
             "| Keeper | Distance | Keeper off his line | On target | Saved | Goals | Missed | Blocked |"
             " Unresolved |",
             "|---|---|---|---|---|---|---|---|---|"]
    for (dist, spot), r in zip(jobs, runs, strict=True):
        on = r["goal"] + r["on_target"]
        saved = f"{r['on_target'] / on:.0%}" if on else "n/a"
        keeper = "O1" if spot == "o1" else "on his line"
        lines.append(f"| {keeper} | {dist} m | {r['depth']:.1f} m | {on:g} | {saved} | {r['goal']:g} | "
                     f"{r['off_target']:g} | {r['blocked']:g} | {r['unresolved']:g} |")
    Path(args.out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines[4:]))


if __name__ == "__main__":
    main()
