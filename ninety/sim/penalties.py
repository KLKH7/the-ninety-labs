"""Penalty kicks taken in isolation: how often they are scored, how often the keeper goes the right
way, and how often he stops them when he does, beside published figures. A report, never a gate:
nothing in the engine is tuned to these numbers (docs/GROUNDING.md).

    uv run python -m ninety.sim.penalties    # 600 penalties; writes docs/eval/penalties.md
"""

from __future__ import annotations

import argparse
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from ninety.sim.engine import PENALTY_MARK_M, PITCH_Y, Engine

ROOT = Path(__file__).resolve().parents[2]
GOAL_X = 105.0  # the away side defends this goal; the home side takes the kick
SETTLE_S = 3.0  # how long everyone has to reach the places Law 14 gives them before the kick
AFTER_S = 3.0  # how long after the kick the ball is followed
# For reading the report only (held-out checks, never targets).
PUBLISHED = {"scored": "75 to 90% (Premier League seasons, Opta via The Analyst)",
             "right_way": "55% (Bar-Eli et al. 2007, Table 1)",
             "right": "about 27% (Bar-Eli et al. 2007, Table 2)",
             "wrong": "about 0% (Bar-Eli et al. 2007, Table 2)"}


def take(seed: int) -> dict[str, bool | None]:
    """One penalty: the home side's best finisher against the away keeper, from the mark."""
    e = Engine(seed)
    taker = max((p for p in e.players if p.team == "home" and p.role != "GK"),
                key=lambda p: p.profile["finishing"])
    spot = (GOAL_X - PENALTY_MARK_M, PITCH_Y / 2)
    e.possessor, e.kicked = None, None
    e.ball = (*spot, 0.0, 0.0, 0.0, 0.0)
    e.stop("penalty_kick", "home", spot, taker.id)
    e.restart.ready_at = e.t + SETTLE_S
    for p in e.players:
        p.vx = p.vy = 0.0
        if p is not taker:
            p.x, p.y = e.penalty_wait_spot(p)
    taker.x, taker.y, taker.heading = spot[0] - 1.0, spot[1], 0.0
    shot = None
    for _ in range(int((SETTLE_S + 5.0) * 25)):
        e.step()
        shot = next((ev for ev in e.match.events if ev["type"] == "shot"), None)
        if shot:
            break
    if shot is None:
        return {"taken": False}
    side = 1.0 if e.ball[4] > 0 else -1.0  # where the kick went, as struck
    crossing = e.ball_at_x(GOAL_X)  # (seconds, y, height) where its own flight takes it over the line
    read = e.read[1] if e.read else None
    keeper_touched = False
    for _ in range(int(AFTER_S * 25)):
        keeper_touched = keeper_touched or e.shot_touched_by == "keeper"
        if any(ev["type"] == "goal" for ev in e.match.events) or e.kicked is not shot:
            break
        e.step()
    goal = any(ev["type"] == "goal" for ev in e.match.events)
    return {"taken": True, "goal": goal, "keeper": keeper_touched and not goal,
            "on_target": goal or shot.get("outcome") == "on_target",
            "right_way": None if read is None else (read - PITCH_Y / 2) * side > 0,
            "flight": crossing and crossing[0], "wide": crossing and abs(crossing[1] - PITCH_Y / 2),
            "high": crossing and crossing[2]}


def rate(rows: list[dict], key: str) -> str:
    return f"{sum(bool(r[key]) for r in rows) / len(rows):.0%} of {len(rows)}" if rows else "none"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--n", type=int, default=600)
    ap.add_argument("--out", default=str(ROOT / "docs/eval/penalties.md"))
    args = ap.parse_args()
    with ProcessPoolExecutor() as pool:
        rows = [r for r in pool.map(take, range(1, args.n + 1), chunksize=8) if r["taken"]]
    right = [r for r in rows if r["right_way"]]
    wrong = [r for r in rows if r["right_way"] is False]
    lines = ["# Penalties", "",
             f"Generated by `uv run python -m ninety.sim.penalties` on {args.n} penalties (seeds 1 to "
             f"{args.n}), each the home side's best finisher against the away keeper. A report beside "
             "published figures, never a target.", "",
             "| Measure | Engine | Published |", "|---|---|---|"]
    for label, value, key in (("scored", rate(rows, "goal"), "scored"),
                              ("keeper went the way it was kicked", rate(rows, "right_way"), "right_way"),
                              ("stopped by the keeper, right way", rate(right, "keeper"), "right"),
                              ("stopped by the keeper, wrong way", rate(wrong, "keeper"), "wrong"),
                              ("on target", rate(rows, "on_target"), "")):
        lines.append(f"| {label} | {value} | {PUBLISHED.get(key, '')} |")
    Path(args.out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines[4:]))


if __name__ == "__main__":
    main()
